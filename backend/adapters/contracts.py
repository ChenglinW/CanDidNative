"""Agent memory-read seam; the full proposed service contract is documented separately."""
from typing import Protocol


class AgentMemoryAdapter(Protocol):
    name: str
    contract_version: str

    def get_occasion(self, owner: str, occasion_id: str, workspace_id: str | None = None) -> dict: ...

    def query(self, owner: str, name: str, args: dict, sources: list,
              occasion_id: str | None = None, workspace_id: str | None = None) -> dict: ...

    def search(self, owner: str, query: str, *, occasion_id: str | None = None,
               session_id: str | None = None, limit: int = 6,
               confirmed_only: bool = True, sources: list | None = None, workspace_id: str | None = None) -> dict: ...

    def read_evidence(self, owner: str, references: list[dict], *, sources: list | None = None, workspace_id: str | None = None) -> dict: ...

    def references_status(self, owner: str, references: list[dict], workspace_id: str | None = None) -> list[dict]: ...

    def decorate_message(self, owner: str, message: dict, workspace_id: str | None = None) -> dict: ...

    def profile(self, owner: str) -> dict: ...


class BusinessMemoryAdapter(AgentMemoryAdapter, Protocol):
    """Domain reads and writes must migrate together; no remote implementation is guessed."""
    def get(self, table: str, owner: str, id: str) -> dict: ...
    def rows(self, table: str, owner: str, **filters) -> list[dict]: ...
    def put(self, table: str, owner: str, data: dict, *args, **kwargs) -> dict: ...
    def update(self, table: str, owner: str, id: str, patch: dict, **kwargs) -> dict: ...
    def remove(self, table: str, owner: str, id: str) -> None: ...
    def create_session(self, owner: str, data: dict) -> dict: ...
    def mutate_asset(self, owner: str, id: str, **kwargs) -> dict: ...
    def context(self, owner: str, *args, **kwargs) -> dict: ...
